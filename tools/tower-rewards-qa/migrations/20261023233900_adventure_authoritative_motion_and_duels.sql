create function versus_private.adventure_duel_advance(p_state jsonb,p_now timestamptz) returns jsonb
language plpgsql security definer set search_path='' as $$
declare s jsonb:=p_state;next_ timestamptz;impact_ timestamptz;tick_ timestamptz;deadline_ timestamptz;e jsonb;
 a jsonb;effect_ text;word_ text;alphabet_ text;correct_ text[];wrong_ text[];options_ text[];letter_ text;prob_ double precision;old_index integer;iterations integer:=0;
begin
 if not (s->>'started')::boolean or (s->>'finished')::boolean then return s;end if;
 loop
  exit when (s->>'finished')::boolean;
  iterations:=iterations+1;if iterations>1024 then raise exception 'Demasiados eventos de duelo.' using errcode='54000';end if;
  select min((value->>'impact_at')::timestamptz) into impact_ from jsonb_array_elements(s->'pending');
  tick_:=case when (s->'npc'->>'finished')::boolean then null else (s->>'next_tick')::timestamptz end;
  deadline_:=least(case when not(s->'player'->>'finished')::boolean then (s->'player'->>'deadline')::timestamptz end,case when not(s->'npc'->>'finished')::boolean then (s->'npc'->>'deadline')::timestamptz end);
  next_:=least(impact_,tick_,deadline_);exit when next_ is null or next_>p_now;
  if deadline_=next_ then s:=versus_private.adventure_duel_resolve(s,next_);exit when (s->>'finished')::boolean;
  elsif impact_=next_ then
   select value into e from jsonb_array_elements(s->'pending') where (value->>'impact_at')::timestamptz=impact_ limit 1;
   s:=jsonb_set(s,'{pending}',coalesce((select jsonb_agg(value) from jsonb_array_elements(s->'pending') where value<>e),'[]'::jsonb));
   s:=versus_private.adventure_duel_impact(s,e,next_);
  else
   s:=jsonb_set(s,'{next_tick}',to_jsonb(tick_+make_interval(secs=>(s->'config'->>'interval')::numeric/1000)));
   a:=s->'npc';effect_:=case when (a->>'effect_until')::timestamptz>tick_ then a->>'effect' else '' end;
   if effect_ in ('roots','black_hole','key_bounce','ice_screen','key_theft','time_steal','forced_miss') then continue;end if;
   s:=versus_private.adventure_duel_ability(s,'npc',tick_);a:=s->'npc';old_index:=(a->>'index')::integer;
   word_:=versus_private.adventure_duel_word(s,'npc');alphabet_:=case when s->>'language'='es' then 'QWERTYUIOPASDFGHJKLÑZXCVBNM' else 'QWERTYUIOPASDFGHJKLZXCVBNM' end;
   select array_agg(letter order by first_) into correct_ from (select substr(word_,i,1) letter,min(i) first_ from generate_series(1,length(word_)) i group by substr(word_,i,1)) q where not(a->'letters' @> jsonb_build_array(letter));
   select array_agg(substr(alphabet_,i,1) order by i) into wrong_ from generate_series(1,length(alphabet_)) i where position(substr(alphabet_,i,1) in word_)=0 and not(a->'letters' @> jsonb_build_array(substr(alphabet_,i,1)));
   prob_:=case when effect_ in ('roar','shuffle') then 0.25 else (s->'config'->>'probability')::double precision end;
   if coalesce(a->>'hint','')<>'' then letter_:=a->>'hint';
   else
    options_:=case when random()<prob_ or cardinality(wrong_) is null then correct_ else wrong_ end;
    letter_:=options_[1+floor(random()*cardinality(options_))::integer];
   end if;
   if letter_ is null then continue;end if;
   s:=versus_private.adventure_duel_letter(s,'npc',letter_,tick_);
   if not (s->>'finished')::boolean and (s->'npc'->>'index')::integer=old_index then s:=versus_private.adventure_duel_ability(s,'npc',tick_);end if;
  end if;
 end loop;
 return versus_private.adventure_duel_resolve(s,p_now);
end $$;
revoke all on function versus_private.adventure_duel_advance(jsonb,timestamptz) from public,anon,authenticated,service_role;

create function versus_private.adventure_duel_input(p_state jsonb,p_payload jsonb,p_now timestamptz) returns jsonb
language plpgsql security definer set search_path='' as $$
declare s jsonb:=p_state;op text:=p_payload->>'op';a jsonb;effect_ text;
begin
 if op is null or op not in ('start_duel','tick','letter','ability','retry_duel') then raise exception 'Acción de duelo inválida.' using errcode='22023';end if;
 if op='letter' then
  if p_payload-array['op','letter','word']<>'{}'::jsonb then raise exception 'Parámetros de letra inválidos.' using errcode='22023';end if;
 elsif p_payload-'op'<>'{}'::jsonb then raise exception 'Parámetros de duelo inválidos.' using errcode='22023';end if;
 if op='retry_duel' then
  if p_payload-'op'<>'{}'::jsonb or not (s->>'finished')::boolean or s->>'winner'='player' then raise exception 'Reintento no permitido.' using errcode='22023';end if;
  return versus_private.adventure_duel_initial(s->>'kind',s->>'language',p_now)||jsonb_build_object('reduced',(s->>'reduced')::boolean);
 end if;
 if op='start_duel' then
  if p_payload-'op'<>'{}'::jsonb then raise exception 'Inicio inválido.' using errcode='22023';end if;
  if (s->>'started')::boolean then return versus_private.adventure_duel_advance(s,p_now);end if;
  s:=s||jsonb_build_object('started',true,'started_at',p_now,'next_tick',p_now+make_interval(secs=>(s->'config'->>'interval')::numeric/1000));
  s:=jsonb_set(jsonb_set(s,'{player,deadline}',to_jsonb(p_now+interval '240 seconds')),'{npc,deadline}',to_jsonb(p_now+interval '240 seconds'));
  return s;
 end if;
 if not (s->>'started')::boolean then raise exception 'El duelo no comenzó.' using errcode='22023';end if;
 s:=versus_private.adventure_duel_advance(s,p_now);
 if (s->>'finished')::boolean then return s;end if;
 if op='tick' then
  if p_payload-'op'<>'{}'::jsonb then raise exception 'Pulso inválido.' using errcode='22023';end if;
 elsif op='ability' then
  if p_payload-'op'<>'{}'::jsonb then raise exception 'Habilidad inválida.' using errcode='22023';end if;
  s:=versus_private.adventure_duel_ability(s,'player',p_now);
 elsif op='letter' then
  if p_payload-array['op','letter','word']<>'{}'::jsonb or jsonb_typeof(p_payload->'letter') is distinct from 'string' or jsonb_typeof(p_payload->'word') is distinct from 'number' or (p_payload->>'word')!~ '^[0-9]{1,2}$' then raise exception 'Letra de duelo inválida.' using errcode='22023';end if;
  a:=s->'player';
  if (a->>'index')::integer<>(p_payload->>'word')::integer then return s||jsonb_build_object('feedback','stale_word');end if;
  effect_:=case when (a->>'effect_until')::timestamptz>p_now then a->>'effect' else '' end;
  if effect_ in ('roots','black_hole','key_bounce','ice_screen','key_theft','time_steal','forced_miss') then return s||jsonb_build_object('feedback','blocked');end if;
  s:=versus_private.adventure_duel_letter(s,'player',p_payload->>'letter',p_now);
 end if;
 return s;
end $$;
