  a:=s->target_;a:=a||jsonb_build_object('deadline',(a->>'deadline')::timestamptz-interval '20 seconds','effect','time_steal','effect_until',p_now+interval '2 seconds');s:=jsonb_set(s,array[target_],a);
 elsif effect_='forced_miss' then
  a:=s->target_;a:=a||jsonb_build_object('effect','forced_miss','effect_until',p_now+interval '2 seconds');s:=jsonb_set(s,array[target_],a);
  e:=jsonb_build_object('actor',actor_,'kind','forced_letter','impact_at',p_now+interval '2 seconds','word_index',(a->>'index')::integer);
  s:=jsonb_set(s,'{pending}',s->'pending'||jsonb_build_array(e));
 elsif effect_='forced_letter' then
  a:=s->target_;
  if (a->>'index')::integer=(p_event->>'word_index')::integer and not (a->>'finished')::boolean then
   word_:=versus_private.adventure_duel_word(s,target_);alphabet_:=case when s->>'language'='es' then 'QWERTYUIOPASDFGHJKLÑZXCVBNM' else 'QWERTYUIOPASDFGHJKLZXCVBNM' end;
