create function versus_private.adventure_maze_input(p_state jsonb,p_definition jsonb,p_payload jsonb,p_now timestamptz) returns jsonb
language plpgsql set search_path='' as $$
declare s jsonb:=p_state;x double precision:=(s->>'x')::double precision;y double precision:=(s->>'y')::double precision;
 vx double precision:=(s->>'vx')::double precision;vy double precision:=(s->>'vy')::double precision;
 fx double precision:=(s->>'force_x')::double precision;fy double precision:=(s->>'force_y')::double precision;new_fx double precision;new_fy double precision;
 total_ticks integer;steps integer;i integer;speed double precision;done_ boolean:=false;map_ jsonb:=p_definition->'map';
begin
 if p_payload->>'op' is distinct from 'input' or p_payload-array['op','x','y']<>'{}'::jsonb or jsonb_typeof(p_payload->'x') is distinct from 'number' or jsonb_typeof(p_payload->'y') is distinct from 'number' then raise exception 'Entrada de inclinación inválida.' using errcode='22023';end if;
 new_fx:=(p_payload->>'x')::double precision;new_fy:=(p_payload->>'y')::double precision;
 if new_fx not between -1.458333333334 and 1.458333333334 or new_fy not between -1.458333333334 and 1.458333333334 then raise exception 'Fuerza fuera de rango.' using errcode='22023';end if;
 total_ticks:=floor(extract(epoch from p_now-(s->>'started_at')::timestamptz)*60)::integer;
 steps:=total_ticks-(s->>'ticks')::integer;if steps<0 then raise exception 'El reloj del servidor retrocedió.';end if;
 if fx=0 and fy=0 and abs(vx)+abs(vy)<0.000001 then steps:=0;end if;
 if steps>600 then raise exception 'Se interrumpió la simulación online. Repetí la misión.' using errcode='55000';end if;
 for i in 1..steps loop
  vx:=(vx+fx*7.2/60)*0.975;vy:=(vy+fy*7.2/60)*0.975;speed:=sqrt(vx^2+vy^2);
  if speed>4.2 then vx:=vx*4.2/speed;vy:=vy*4.2/speed;end if;
  if not versus_private.adventure_maze_collision(x+vx/60,y,map_) then x:=x+vx/60;else vx:=vx* -0.24;end if;
  if not versus_private.adventure_maze_collision(x,y+vy/60,map_) then y:=y+vy/60;else vy:=vy* -0.24;end if;
  if sqrt((x-19.5)^2+(y-19.5)^2)<0.42 then done_:=true;exit;end if;
 end loop;
 return s||jsonb_build_object('x',x,'y',y,'vx',vx,'vy',vy,'force_x',new_fx,'force_y',new_fy,'ticks',total_ticks,'done',done_);
end $$;
revoke all on function versus_private.adventure_maze_input(jsonb,jsonb,jsonb,timestamptz) from public,anon,authenticated,service_role;
