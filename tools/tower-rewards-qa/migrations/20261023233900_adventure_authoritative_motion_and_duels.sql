create function versus_private.adventure_duel_letter(p_state jsonb,p_actor text,p_letter text,p_now timestamptz) returns jsonb
language plpgsql security definer set search_path='' as $$
declare s jsonb:=p_state;a jsonb:=s->p_actor;other_ text:=case when p_actor='player' then 'npc' else 'player' end;b jsonb:=s->other_;word_ text;letters_ text[];won boolean;failed boolean;extra_ integer;amount_ integer;idx integer;
begin
 if (s->>'finished')::boolean or (a->>'finished')::boolean then return s;end if;
 word_:=versus_private.adventure_duel_word(s,p_actor);if word_ is null then raise exception 'No hay palabra activa.';end if;
 if p_letter is null or length(p_letter)<>1 or position(p_letter in case when s->>'language'='es' then 'QWERTYUIOPASDFGHJKLÑZXCVBNM' else 'QWERTYUIOPASDFGHJKLZXCVBNM' end)=0 then raise exception 'Letra inválida.' using errcode='22023';end if;
 if a->'letters' @> jsonb_build_array(p_letter) then return s;end if;
 a:=jsonb_set(a,'{letters}',a->'letters'||to_jsonb(p_letter));
 amount_:=length(word_)-length(replace(word_,p_letter,''));
 if amount_>0 then a:=jsonb_set(a,'{charge}',to_jsonb(least(8,(a->>'charge')::integer+amount_)));else a:=jsonb_set(a,'{errors}',to_jsonb((a->>'errors')::integer+1));end if;
 if a->>'hint'=p_letter then a:=jsonb_set(a,'{hint}','""');end if;
 select coalesce(array_agg(value),'{}') into letters_ from jsonb_array_elements_text(a->'letters');
 won:=not exists(select 1 from generate_series(1,length(word_)) i where not substr(word_,i,1)=any(letters_));failed:=(a->>'errors')::integer>=6;
 s:=versus_private.adventure_duel_event(s,jsonb_build_object('type','letter','actor',p_actor,'letter',p_letter,'correct',amount_>0));
 if won or failed then
  idx:=(a->>'index')::integer+1;a:=a||jsonb_build_object('index',idx,'letters','[]'::jsonb,'errors',0,'hint','');
  if won then a:=jsonb_set(a,'{completed}',to_jsonb((a->>'completed')::integer+1));b:=jsonb_set(b,'{lives}',to_jsonb((b->>'lives')::integer-1));
  else
   a:=jsonb_set(a,'{lives}',to_jsonb((a->>'lives')::integer-1));
   if (a->>'lives')::integer>0 then
    select w.word_id into extra_ from versus_private.adventure_duel_words w where w.language=s->>'language' and w.theme=a->>'theme' and not (a->'words' @> to_jsonb(array[w.word_id])) order by gen_random_uuid() limit 1;
    if extra_ is not null then a:=jsonb_set(a,'{words}',a->'words'||to_jsonb(extra_));end if;
   end if;
  end if;
  if (a->>'completed')::integer>=5 then a:=jsonb_set(a,'{finished}','true');end if;
  if a->>'effect'='forced_miss' then a:=a||jsonb_build_object('effect','','effect_until',null);end if;
  s:=versus_private.adventure_duel_event(s,jsonb_build_object('type','word','actor',p_actor,'correct',won,'reveal',case when failed then word_ else null end));
 end if;
 s:=jsonb_set(jsonb_set(s,array[p_actor],a),array[other_],b);
 return versus_private.adventure_duel_resolve(s,p_now);
end $$;
revoke all on function versus_private.adventure_duel_letter(jsonb,text,text,timestamptz) from public,anon,authenticated,service_role;

