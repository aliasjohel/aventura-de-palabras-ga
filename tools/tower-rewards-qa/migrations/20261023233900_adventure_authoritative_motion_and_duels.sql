create function versus_private.adventure_duel_resolve(p_state jsonb,p_now timestamptz) returns jsonb language plpgsql set search_path='' as $$
 declare s jsonb:=p_state;p jsonb:=s->'player';n jsonb:=s->'npc';winner_ text:='';pt timestamptz;nt timestamptz;
begin
 if (s->>'finished')::boolean or not (s->>'started')::boolean then return s;end if;
 pt:=case when not (p->>'finished')::boolean then (p->>'deadline')::timestamptz end;
 nt:=case when not (n->>'finished')::boolean then (n->>'deadline')::timestamptz end;
 if (p->>'lives')::integer<=0 then winner_:='npc';elsif (n->>'lives')::integer<=0 then winner_:='player';
 elsif pt<=p_now and nt<=p_now and pt=nt then winner_:=case when (p->>'lives')::integer>(n->>'lives')::integer then 'player' when (p->>'lives')::integer<(n->>'lives')::integer then 'npc' else 'draw' end;
 elsif pt<=p_now and (nt>p_now or pt<nt) then winner_:='npc';elsif nt<=p_now then winner_:='player';
 elsif (p->>'finished')::boolean and (n->>'finished')::boolean then winner_:=case when (p->>'lives')::integer>(n->>'lives')::integer then 'player' when (p->>'lives')::integer<(n->>'lives')::integer then 'npc' else 'draw' end;
 end if;
 if winner_<>'' then
  s:=s||jsonb_build_object('finished',true,'winner',winner_,'done',winner_='player','finished_at',p_now);
  s:=versus_private.adventure_duel_event(s,jsonb_build_object('type','result','winner',winner_));
 end if;
 return s;
end $$;
revoke all on function versus_private.adventure_duel_resolve(jsonb,timestamptz) from public,anon,authenticated,service_role;

