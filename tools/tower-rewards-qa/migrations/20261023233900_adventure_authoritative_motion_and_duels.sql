 select jsonb_agg(word_id) into words_ from (select word_id from versus_private.adventure_duel_words where language=p_language and theme=theme_ order by gen_random_uuid() limit 5) q;
 if jsonb_array_length(words_)<>5 then raise exception 'Banco de duelo incompleto.';end if;
 return jsonb_build_object('theme',theme_,'words',words_,'index',0,'letters','[]'::jsonb,'errors',0,'lives',5,'completed',0,'charge',0,'hint','','finished',false,'effect','','effect_until',null,'deadline',null);
end $$;
