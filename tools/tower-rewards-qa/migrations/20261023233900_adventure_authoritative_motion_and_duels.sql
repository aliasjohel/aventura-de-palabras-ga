create function versus_private.adventure_maze_collision(p_x double precision,p_y double precision,p_map jsonb) returns boolean
language plpgsql immutable set search_path='' as $$
declare row_ integer;col_ integer;nx double precision;ny double precision;
begin
 for row_ in floor(p_y-0.27)::integer..floor(p_y+0.27)::integer loop
  for col_ in floor(p_x-0.27)::integer..floor(p_x+0.27)::integer loop
   if row_>=0 and col_>=0 and row_<jsonb_array_length(p_map) and col_<length(p_map->>row_) and substr(p_map->>row_,col_+1,1)='0' then continue;end if;
   nx:=greatest(col_,least(p_x,col_+1));ny:=greatest(row_,least(p_y,row_+1));
   if (p_x-nx)^2+(p_y-ny)^2<0.27^2 then return true;end if;
  end loop;
 end loop;return false;
end $$;
