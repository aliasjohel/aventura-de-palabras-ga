returns jsonb language plpgsql security definer set search_path='' as $$
declare a versus_private.adventure_reward_attempts;s versus_private.adventure_validation_sessions;
 w versus_private.adventure_validation_words;phases jsonb;kind text;mask jsonb;
begin
 select * into a from versus_private.adventure_reward_attempts where id=p_attempt and user_id=auth.uid();
 if not found then raise exception 'Intento no disponible.' using errcode='42501';end if;
 select * into s from versus_private.adventure_validation_sessions where attempt_id=a.id;
 select c.phases into phases from versus_private.adventure_validation_catalog c where c.world=a.world and c.mission=a.mission;
 kind:=phases->>s.phase;
 if kind='word' then
  select * into strict w from versus_private.adventure_validation_words where language=s.language and world=a.world and word_id=s.word_ids[s.phase+1];
  select jsonb_agg(case when substr(w.word_key,i,1)=any(s.letters) or s.errors=6 then to_jsonb(substr(w.word,i,1)) else 'null'::jsonb end order by i)
   into mask from generate_series(1,length(w.word_key)) i;
 end if;
 return jsonb_build_object('version','sql-actions-v1','attemptId',a.id,'world',a.world,'mission',a.mission,'language',s.language,
  'phase',s.phase,'kind',kind,'sequence',s.sequence,'phaseDone',s.phase_done,'complete',s.complete,
  'mask',mask,'hint',w.hint,'letters',s.letters,'errors',s.errors,'board',s.board,'detail',case when kind like 'duel:%' then versus_private.adventure_duel_view(s.detail,versus_private.adventure_server_now()) else s.detail end,
  'word',case when s.phase_done or s.errors=6 then w.word else null end);
end $$;
