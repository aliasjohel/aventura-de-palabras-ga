-- Diccionario temático del modo versus: 50 palabras por cada una de las 10 categorías.
-- Se guarda fuera del esquema expuesto y un trigger impide desafíos inventados,
-- conservando la equivalencia entre vocales acentuadas y sin acento.

create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

create table private.versus_word_dictionary (
  theme_key text not null check (
    theme_key in (
      'paises', 'frutas', 'animales', 'comidas', 'profesiones',
      'deportes', 'transportes', 'objetos', 'naturaleza', 'nombres'
    )
  ),
  word text not null check (
    char_length(word) between 3 and 12
    and word ~ '^[A-ZÁÉÍÓÚÜÑ]+$'
  ),
  word_key text generated always as (public.versus_letter_key(word)) stored,
  primary key (theme_key, word_key)
);

alter table private.versus_word_dictionary enable row level security;
revoke all on table private.versus_word_dictionary from public, anon, authenticated;

