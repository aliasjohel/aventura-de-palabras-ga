create or replace function private.validate_versus_challenge_dictionary()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if exists (
    select 1
    from unnest(new.words) as supplied(word)
    where not exists (
      select 1
      from private.versus_word_dictionary as dictionary
      where dictionary.theme_key = new.theme_key
        and dictionary.word_key = public.versus_letter_key(supplied.word)
    )
  ) then
    raise exception 'Una o más palabras no figuran en el diccionario de la temática.';
  end if;

  return new;
end;
$$;

revoke execute on function private.validate_versus_challenge_dictionary()
  from public, anon, authenticated;

create trigger validate_versus_challenge_dictionary
before insert or update of theme_key, words
on public.versus_challenges
for each row
execute function private.validate_versus_challenge_dictionary();


