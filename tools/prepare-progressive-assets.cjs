// Derive the browser catalogue from the worker, without changing media bytes.
const fs = require('node:fs'), vm = require('node:vm'), path = require('node:path');
const root = path.resolve(__dirname, '..');
const context = { self: { addEventListener() {} }, URL, Request, Response };
vm.runInNewContext(fs.readFileSync(path.join(root, 'sw.js'), 'utf8') + '\nglobalThis.catalogue = RESOURCE_ASSETS;', context);
const output = '/* Generated by tools/prepare-progressive-assets.cjs. */\n' +
  'globalThis.GameResourceCatalog = Object.freeze(' + JSON.stringify(Array.from(context.catalogue), null, 2) + ');\n';
const target = path.join(root, 'js/resource-catalog.js');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== output) throw Error('Resource catalogue is stale');
} else fs.writeFileSync(target, output);
